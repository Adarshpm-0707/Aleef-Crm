/**
 * components/layout/EmployeeSidebar.tsx
 *
 * Dedicated responsive navigation sidebar for the Employee Portal.
 */
"use client";

import React, { useEffect, useState } from "react";
import { SidebarBase, type NavItem } from "./SidebarBase";
import { tasksApi, deliverablesApi } from "@/lib/api";
import { useCurrentEmployee } from "@/lib/permissions/employee";

export function EmployeeSidebar({
  mobileOpen,
  onMobileClose,
  activeHref,
}: {
  mobileOpen: boolean;
  onMobileClose: () => void;
  activeHref?: string;
}) {
  const { employee } = useCurrentEmployee();
  const [activeTasksCount, setActiveTasksCount] = useState<number>(2);
  const [pendingUploadsCount, setPendingUploadsCount] = useState<number>(1);

  useEffect(() => {
    async function fetchBadges() {
      try {
        const [tasks, deliverables] = await Promise.all([
          tasksApi.getAll({ assigneeId: employee.userId }),
          deliverablesApi.getAll({ employeeUserId: employee.userId }),
        ]);
        const active = tasks.filter((t) => t.status === "in_progress" || t.status === "todo").length;
        const pending = deliverables.filter((d) => d.status === "pending_review").length;
        setActiveTasksCount(active);
        setPendingUploadsCount(pending);
      } catch {
        // fallback to defaults
      }
    }
    fetchBadges();
  }, [employee.userId]);

  const navItems: NavItem[] = [
    {
      label: "Dashboard",
      href: "/employee/dashboard",
      icon: "M2.25 12l8.954-8.955c.44-.439 1.152-.439 1.591 0L21.75 12M4.5 9.75v10.125c0 .621.504 1.125 1.125 1.125H9.75v-4.875c0-.621.504-1.125 1.125-1.125h2.25c.621 0 1.125.504 1.125 1.125V21h4.125c.621 0 1.125-.504 1.125-1.125V9.75M8.25 21h8.25",
    },
    {
      label: "Client Work",
      href: "/employee/client-work",
      icon: "M20.25 14.15v4.25c0 1.094-.787 2.036-1.872 2.18-2.087.277-4.216.42-6.378.42s-4.291-.143-6.378-.42c-1.085-.144-1.872-1.086-1.872-2.18v-4.25m16.5 0a2.18 2.18 0 00.75-1.661V8.706c0-1.081-.768-2.015-1.837-2.175a48.114 48.114 0 00-3.413-.387m4.5 8.006c-.194.165-.42.295-.673.38A23.978 23.978 0 0112 15.75c-2.648 0-5.195-.429-7.577-1.22a2.016 2.016 0 01-.673-.38m0 0A2.18 2.18 0 013 12.489V8.706c0-1.081.768-2.015 1.837-2.175a48.111 48.111 0 013.413-.387m7.5 0V5.25A2.25 2.25 0 0013.5 3h-3a2.25 2.25 0 00-2.25 2.25v.894m7.5 0a48.667 48.667 0 00-7.5 0M12 12.75h.008v.008H12v-.008z",
      badge: activeTasksCount > 0 ? activeTasksCount : undefined,
    },
    {
      label: "Work Scheduling",
      href: "/employee/schedule",
      icon: "M6.75 3v2.25M17.25 3v2.25M3 18.75V7.5a2.25 2.25 0 012.25-2.25h13.5A2.25 2.25 0 0121 7.5v11.25m-18 0A2.25 2.25 0 005.25 21h13.5A2.25 2.25 0 0021 18.75m-18 0v-7.5A2.25 2.25 0 015.25 9h13.5A2.25 2.25 0 0121 11.25v7.5",
    },
    {
      label: "Leave",
      href: "/employee/leave",
      icon: "M9 12h3.75M9 15h3.75M9 18h3.75m3 .75H18a2.25 2.25 0 002.25-2.25V6.108c0-1.135-.845-2.098-1.976-2.192a48.424 48.424 0 00-1.123-.08m-5.801 0c-.065.21-.1.433-.1.664 0 .414.336.75.75.75h4.5a.75.75 0 00.75-.75 2.25 2.25 0 00-.1-.664m-5.8 0A2.251 2.251 0 0113.5 2.25H15c1.012 0 1.867.668 2.15 1.586m-5.8 0c-.376.023-.75.05-1.124.08C9.095 4.01 8.25 4.973 8.25 6.108V8.25m0 0H4.875c-.621 0-1.125.504-1.125 1.125v11.25c0 .621.504 1.125 1.125 1.125h9.75c.621 0 1.125-.504 1.125-1.125V9.375c0-.621-.504-1.125-1.125-1.125H8.25z",
    },
    {
      label: "Attendance",
      href: "/employee/attendance",
      icon: "M12 6v6h4.5m4.5 0a9 9 0 11-18 0 9 9 0 0118 0z",
    },
    {
      label: "Progress Track",
      href: "/employee/progress",
      icon: "M3.75 3v11.25A2.25 2.25 0 006 16.5h2.25M3.75 3h-1.5m1.5 0h16.5m0 0h1.5m-1.5 0v11.25A2.25 2.25 0 0118 16.5h-2.25m-7.5 0h7.5m-7.5 0l-1 3m8.5-3l1 3m0 0l.5 1.5m-.5-1.5h-9.5m0 0l-.5 1.5",
    },
    {
      label: "Work Uploading",
      href: "/employee/work-upload",
      icon: "M3 16.5v2.25A2.25 2.25 0 005.25 21h13.5A2.25 2.25 0 0021 18.75V16.5m-13.5-9L12 3m0 0l4.5 4.5M12 3v13.5",
      badge: pendingUploadsCount > 0 ? `${pendingUploadsCount} pending` : undefined,
    },
    {
      label: "Reports",
      href: "/employee/reports",
      icon: "M3 13.125C3 12.504 3.504 12 4.125 12h2.25c.621 0 1.125.504 1.125 1.125v6.75C7.5 20.496 6.996 21 6.375 21h-2.25A1.125 1.125 0 013 19.875v-6.75zM9.75 8.625c0-.621.504-1.125 1.125-1.125h2.25c.621 0 1.125.504 1.125 1.125v11.25c0 .621-.504 1.125-1.125 1.125h-2.25a1.125 1.125 0 01-1.125-1.125V8.625zM16.5 4.125c0-.621.504-1.125 1.125-1.125h2.25C20.496 3 21 3.504 21 4.125v15.75c0 .621-.504 1.125-1.125 1.125h-2.25a1.125 1.125 0 01-1.125-1.125V4.125z",
    },
  ];

  const bottomItems: NavItem[] = [
    {
      label: `${employee.fullName} (${employee.departmentName})`,
      href: "/employee/dashboard",
      icon: "M15.75 6a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0zM4.501 20.118a7.5 7.5 0 0114.998 0A17.933 17.933 0 0112 21.75c-2.676 0-5.216-.584-7.499-1.632z",
    },
  ];

  return (
    <SidebarBase
      mobileOpen={mobileOpen}
      onMobileClose={onMobileClose}
      accentColor="indigo"
      roleLabel="Employee"
      navItems={navItems}
      bottomItems={bottomItems}
      activeHref={activeHref}
    />
  );
}
